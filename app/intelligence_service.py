import json
import re

from app.llm_service import call_llm
from app.prompts import (
    get_intelligence_system_prompt,
    build_intelligence_user_prompt
)


TRANSCRIPT_LINE_PATTERN = re.compile(
    r"\[(\d+(?:\.\d+)?)s\s*->\s*(\d+(?:\.\d+)?)s\]\s+"
    r"(.+?):\s*(.*)"
)


def build_speaker_index(transcript: str) -> list[dict]:
    """
    Build a timestamp-indexed lookup from the final speaker-aware transcript.

    Example transcript line:
    [38.00s -> 40.00s] Bob: I'll retest the issue tomorrow.
    """

    entries = []

    for line in (transcript or "").splitlines():
        match = TRANSCRIPT_LINE_PATTERN.match(line.strip())

        if not match:
            continue

        start = float(match.group(1))
        end = float(match.group(2))
        speaker = match.group(3).strip()
        text = match.group(4).strip()

        entries.append({
            "start": start,
            "end": end,
            "speaker": speaker,
            "text": text,
        })

    return entries


def attach_speakers_to_evidence(
    intelligence: dict,
    transcript: str,
) -> dict:
    """
    Attach the actual speaker from the transcript to every evidence item.

    Speaker attribution is deterministic and never generated by the LLM.
    """

    speaker_index = build_speaker_index(transcript)

    if not speaker_index:
        return intelligence

    evidence_categories = [
        "topics",
        "decisions",
        "action_items",
        "risks_and_concerns",
        "unresolved_questions",
        "contradictions",
    ]

    for category in evidence_categories:
        items = intelligence.get(category, [])

        if not isinstance(items, list):
            continue

        for item in items:
            if not isinstance(item, dict):
                continue

            evidence = item.get("evidence", [])

            if not isinstance(evidence, list):
                continue

            for evidence_item in evidence:
                if not isinstance(evidence_item, dict):
                    continue

                timestamp = evidence_item.get("timestamp")

                if not timestamp:
                    continue

                try:
                    timestamp_value = float(
                        re.search(
                            r"\d+(?:\.\d+)?",
                            str(timestamp)
                        ).group()
                    )
                except (AttributeError, ValueError):
                    continue

                best_match = None
                best_distance = float("inf")

                for segment in speaker_index:
                    # Prefer timestamps that fall inside the transcript segment.
                    if segment["start"] <= timestamp_value <= segment["end"]:
                        best_match = segment
                        break

                    # Otherwise keep the closest segment start as fallback.
                    distance = abs(
                        segment["start"] - timestamp_value
                    )

                    if distance < best_distance:
                        best_distance = distance
                        best_match = segment

                if best_match:
                    evidence_item["speaker"] = best_match["speaker"]

    return intelligence


def generate_meeting_intelligence(
    topic: str,
    transcript: str
) -> dict:

    system_prompt = get_intelligence_system_prompt()

    user_prompt = build_intelligence_user_prompt(
        topic,
        transcript
    )

    raw_response = call_llm(
        system_prompt,
        user_prompt
    )

    print("\n===== RAW LLM RESPONSE =====")
    print(raw_response)
    print("===== END RAW LLM RESPONSE =====\n")

    try:
        intelligence = json.loads(raw_response)

        intelligence = attach_speakers_to_evidence(
            intelligence,
            transcript
        )

        return intelligence

    except json.JSONDecodeError:
        return {
            "executive_summary": "Unable to parse meeting intelligence.",
            "topics": [],
            "decisions": [],
            "action_items": [],
            "risks_and_concerns": [],
            "unresolved_questions": [],
            "contradictions": []
        }